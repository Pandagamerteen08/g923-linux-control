"""Compatibility bridge for systems managed with Oversteer.

Oversteer has no scripting interface: it applies settings by writing the same
sysfs attributes this application writes directly, and keeps its own profiles
in a JSON file under the user's configuration directory.  When the kernel
attributes are not writable (for example because a distribution ships a
read-only driver binding), the bridge exports a preset document in Oversteer's
profile directory so the values can be reviewed/applied with that tool.

The bridge only ever *creates* one additional file; it never edits or deletes
Oversteer's own profiles.
"""

from __future__ import annotations

import importlib.util
import json
import logging
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from ..config import SteeringSettings, default_config_dir

log = logging.getLogger(__name__)

PRESET_SCHEMA = "g923-linux-control/oversteer-preset@1"
_SAFE_NAME = re.compile(r"[^a-z0-9_-]+")


@dataclass(frozen=True, slots=True)
class OversteerStatus:
    """Detection result shown in the steering page footer."""

    installed: bool
    profile_dir: str = ""
    executable: str = ""

    @property
    def summary(self) -> str:
        if not self.installed:
            return "Oversteer not detected"
        location = self.executable or self.profile_dir or "installed"
        return f"Oversteer detected ({location})"


class OversteerBridge:
    """Detect Oversteer and export the current wheel settings as a preset."""

    def __init__(
        self,
        home: Path | None = None,
        fallback_dir: Path | None = None,
    ) -> None:
        self._home = home or Path.home()
        self._fallback_dir = fallback_dir or default_config_dir()

    # -- detection --------------------------------------------------------
    def _profile_dir(self) -> Path:
        """Locate Oversteer's profile directory, if it exists."""
        candidates = (
            self._home / ".config" / "oversteer" / "profiles",
            self._home / ".local" / "share" / "oversteer" / "profiles",
        )
        for candidate in candidates:
            if candidate.is_dir():
                return candidate
        return candidates[0]

    def status(self) -> OversteerStatus:
        """Return whether Oversteer appears to be installed."""
        executable = shutil.which("oversteer") or ""
        try:
            module_available = importlib.util.find_spec("oversteer") is not None
        except (ImportError, ValueError):
            module_available = False
        profile_dir = self._profile_dir()
        return OversteerStatus(
            installed=bool(executable) or module_available or profile_dir.is_dir(),
            profile_dir=str(profile_dir) if profile_dir.is_dir() else "",
            executable=executable,
        )

    # -- exporting --------------------------------------------------------
    def preset_path(self, profile: str = "Default") -> Path:
        """Choose a stable preset location without touching existing files."""
        slug = _SAFE_NAME.sub("-", profile.lower()).strip("-") or "default"
        profile_dir = self._profile_dir()
        if profile_dir.is_dir():
            return profile_dir / f"g923-linux-control-{slug}.json"
        return self._fallback_dir / f"oversteer-preset-{slug}.json"

    def export_preset(
        self, steering: SteeringSettings, profile: str = "Default"
    ) -> Path:
        """Write a documented JSON preset and return its path.

        The document intentionally uses explicit percentages and degrees so a
        user can compare the values with Oversteer's UI.  It is not silently
        imported by Oversteer; it is a portable record of the same sysfs
        settings this application applies.
        """
        steering = steering.normalized()
        target = self.preset_path(profile)
        document = {
            "schema": PRESET_SCHEMA,
            "note": (
                "Generated by G923 Linux Control. Values mirror the kernel sysfs "
                "attributes used by Oversteer."
            ),
            "profile": profile,
            "steering": {
                "range_degrees": steering.rotation_deg,
                "gain_percent": steering.ffb_gain,
                "damper_percent": steering.damper,
                "spring_percent": steering.spring,
            },
        }
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            json.dumps(document, indent=2) + "\n", encoding="utf-8"
        )
        log.info("Exported Oversteer preset to %s", target)
        return target
